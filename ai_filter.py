def contains_keyword(text: str, keywords: list) -> bool:
    """Проверяет наличие хотя бы одного ключевого слова или эмодзи."""
    low = text.lower().replace("ё", "е")
    for kw in keywords:
        kw_norm = kw.lower().replace("ё", "е")
        if not re.search(r'^\w+$', kw_norm, re.UNICODE):
            if kw_norm in low:
                return True
        else:
            pattern = r'(?:\b|^)' + re.escape(kw_norm) + r'(?:\b|$)'
            if re.search(pattern, low):
                return True
    return False


