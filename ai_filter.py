def analyze_text_by_keywords(text: str) -> dict:
    """
    Чистый, детерминированный анализ по ключевым словам.
    Возвращает dict с полями:
    {
        "relevant": bool,
        "location": str,
        "status": str,
        "summary": str,
        "engine": "keywords"
    }
    """
    clean_text = text.strip()
    if len(clean_text) < 3:
        return {"relevant": False, "reason": "слишком короткое"}

    # 1. Спам и реклама
    if is_spam_or_promo(clean_text):
        return {"relevant": False, "reason": "спам/реклама"}

    # 2. Вопросы (любые вопросительные сообщения отсекаем)
    if is_question(clean_text):
        return {"relevant": False, "reason": "вопрос"}

    low = clean_text.lower()
    loc = find_location(clean_text)
    has_specific_loc = (loc != "Днепр")

    has_cp = contains_keyword(low, CHECKPOINT_KEYWORDS)
    has_tck = contains_keyword(low, TCK_KEYWORDS)
    has_patrol = contains_keyword(low, PATROL_KEYWORDS)
    has_general_danger = contains_keyword(low, GENERAL_DANGER_KEYWORDS)
    has_clear = contains_keyword(low, CLEAR_KEYWORDS)
    has_action = contains_keyword(low, ACTION_KEYWORDS)

    # 3. Чистая обстановка ("Калиновая чисто", "Кротова вог - никого")
    if has_clear and not (has_cp or has_tck or has_patrol or has_general_danger):
        if has_specific_loc or len(clean_text) < 40:
            return {
                "relevant": True,
                "location": loc,
                "status": "Чисто",
                "summary": f"Обстановка спокойная, проезд свободный ({loc})",
                "engine": "keywords"
            }
        return {"relevant": False, "reason": "флуд без локации"}

    has_stand_with_location = has_specific_loc and any(w in low for w in ["стоят", "стоит", "стоять", "стоїть"])

    # 4. Обнаружение опасности
    is_danger = has_cp or has_tck or has_patrol or has_general_danger or has_stand_with_location

    if not is_danger:
        return {"relevant": False, "reason": "нет ключевых слов обстановки"}

    # ЗАЩИТА ОТ ЛОЖНЫХ СРАБАТЫВАНИЙ:
    # Если в сообщении эмоциональное слово ("зеленые", "пидоры", "мусор"),
    # но НЕТ конкретной локации и НЕТ слова действия ("стоят", "проверяют", "тормозят")
    # — это пустой флуд или эмоциональный вброс. Отсекаем!
    if not has_specific_loc and not has_action and not has_cp:
        return {"relevant": False, "reason": "эмоция/флуд без факта и локации"}

    # Определяем статус и описание
    if has_cp:
        status = "Блокпост"
        summary = f"Установлен блокпост ({loc})"
    elif has_tck:
        status = "ТЦК / Проверка"
        summary = f"Зафиксированы сотрудники ТЦК ({loc})"
    elif has_patrol:
        status = "Патруль"
        summary = f"Патрульный экипаж ({loc})"
    elif has_stand_with_location:
        status = "Проверка"
        summary = f"Внимание, стоят на дороге ({loc})"
    else:
        status = "Проверка документов"
        summary = f"Внимание, проверки на дороге ({loc})"

    return {
        "relevant": True,
        "location": loc,
        "status": status,
        "summary": summary,
        "engine": "keywords"
    }


# Обратная совместимость для bot.py
analyze_text_with_cf_ai = analyze_text_by_keywords
