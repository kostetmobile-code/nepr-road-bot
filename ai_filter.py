def answer_user_question_by_keywords(user_question: str, recent_events: list) -> str:
    """
    Мгновенный поиск по актуальной базе событий без обращения к ИИ.
    """
    clean_q = user_question.strip().lower()
    if not recent_events:
        return (
            "ℹ️ На данный момент активных сообщений о блокпостах или проверках в Днепре нет. "
            "На дорогах спокойно."
        )

    # Ищем упоминание локации в вопросе
    target_loc = find_location(clean_q)
    matches = []

    for ev in recent_events:
        ev_loc = ev.get("location", "").lower()
        ev_text = ev.get("raw_text", "").lower()
        ev_summary = ev.get("summary", "").lower()

        # Если нашли конкретную локацию в запросе
        if target_loc != "Днепр":
            if target_loc.lower() in ev_loc or target_loc.lower() in ev_text:
                matches.append(ev)
        else:
            # Ищем по ключевым словам из вопроса
            words = [w for w in re.split(r'\s+', clean_q) if len(w) > 3]
            if any(w in ev_text or w in ev_loc or w in ev_summary for w in words):
                matches.append(ev)

    if matches:
        lines = [f"📍 <b>Информация по вашему запросу («{user_question.strip()}»):</b>\n"]
        for ev in matches[-4:]:
            lines.append(
                f"🕒 <b>{ev.get('time', '')}</b> — 📍 <b>{ev.get('location', '')}</b>\n"
                f"⚠️ <b>{ev.get('status', '')}:</b> {ev.get('summary', '')}\n"
                f"💬 <i>«{ev.get('raw_text', '')[:100]}»</i>\n"
            )
        return "\n".join(lines)

    if target_loc != "Днепр":
        return f"ℹ️ По локации <b>{target_loc}</b> за последнее время сообщений не поступало. Обстановка спокойная."

    return (
        f"ℹ️ По запросу <b>«{user_question.strip()}»</b> свежих предупреждений не зафиксировано.\n"
        "Вы можете нажать <b>«📋 Последняя сводка»</b>, чтобы просмотреть все актуальные события города."
    )


# Обратная совместимость для bot.py
answer_user_question_with_cf_ai = answer_user_question_by_keywords
