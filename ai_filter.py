def find_location(text: str) -> str:
    """Ищет совпадение с известными ориентирами Днепра."""
    low = text.lower().replace("ё", "е")
    for variants, canonical in LOCATIONS_MAP:
        for v in variants:
            v_norm = v.lower().replace("ё", "е")
            pattern = r'(?:\b|^)' + re.escape(v_norm) + r'(?:\b|$)'
            if re.search(pattern, low):
                return canonical
    return "Днепр"


